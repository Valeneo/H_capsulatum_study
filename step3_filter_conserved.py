#!/usr/bin/env python3
"""
Step 3: Multi-Strain BLAST Conservation Filtering for Histoplasma capsulatum
Tools: BLASTn Tabular Output Parser (outfmt 6)

Biology & Logic:
- For a universal diagnostic marker, the flanking regions MUST be conserved across all strains.
- This script parses all pairwise BLASTn tabular results (outfmt 6) generated by aligning
  the extracted flanking sequences against each target genome database.
- Filtering Stringency:
  1. Percent Identity (pident) >= 85.0%
  2. Query Coverage (alignment length / total query length) >= 80.0%
  3. E-value <= 1e-10
  4. Single-copy orthology (retains best hit per target genome)
- Retains only STR loci that pass across ALL evaluated target genomes.
"""

import os
import glob

BLAST_DIR = "blast/outputs"
OUTPUT_DIR = "results/step2_conserved_loci"
os.makedirs(OUTPUT_DIR, exist_ok=True)
OUTPUT_FILE = os.path.join(OUTPUT_DIR, "conserved_loci_metadata.txt")

# Stringency Thresholds
MIN_PIDENT = 85.0     # Min 85% sequence identity
MIN_COVERAGE = 80.0   # Min 80% query flank coverage
MAX_EVALUE = 1e-10    # Strict statistical significance


def parse_blast_tab(file_path):
    """
    Parses BLAST outfmt 6 results.
    Returns: dict mapping query_id -> best valid hit metadata.
    """
    valid_hits = {}
    if not os.path.exists(file_path):
        print(f"  ❌ Error: BLAST file '{file_path}' not found.")
        return valid_hits

    with open(file_path, "r") as f:
        for line in f:
            parts = line.strip().split("\t")
            if len(parts) < 12:
                continue

            qseqid = parts[0]          # Query ID: STR_HC_Strain_0001|contig|start-end|motif
            sseqid = parts[1]          # Subject Contig/Chromosome ID
            pident = float(parts[2])   # Percent Identity
            length = int(parts[3])     # Alignment length
            sstart = int(parts[8])     # Subject Start
            send = int(parts[9])       # Subject End
            evalue = float(parts[10])  # E-value
            bitscore = float(parts[11])

            # Calculate query length: 300 bp 5' flank + 300 bp 3' flank + repeat length
            try:
                coords = qseqid.split("|")[2].split("-")
                repeat_len = int(coords[1]) - int(coords[0]) + 1
                query_total_len = 300 + 300 + repeat_len
            except Exception:
                query_total_len = 620  # Fallback standard length

            coverage = (length / query_total_len) * 100.0

            # Apply quality filters
            if pident >= MIN_PIDENT and coverage >= MIN_COVERAGE and evalue <= MAX_EVALUE:
                # Keep highest bitscore hit per query
                if qseqid not in valid_hits or bitscore > valid_hits[qseqid]["bitscore"]:
                    valid_hits[qseqid] = {
                        "target_chrom": sseqid,
                        "target_start": min(sstart, send),
                        "target_end": max(sstart, send),
                        "pident": pident,
                        "coverage": coverage,
                        "evalue": evalue,
                        "bitscore": bitscore
                    }
    return valid_hits


def main():
    blast_files = glob.glob(os.path.join(BLAST_DIR, "*.tab"))
    if not blast_files:
        print(f"❌ No BLAST tabular results found in '{BLAST_DIR}/'.")
        print(f"   Please run BLASTn of query flanks against target databases first.")
        return

    print(f"🔍 Discovered {len(blast_files)} BLAST result table(s) in '{BLAST_DIR}'.")

    # Parse all target comparison files
    target_hits = {}
    for bf in sorted(blast_files):
        target_name = os.path.splitext(os.path.basename(bf))[0]
        hits = parse_blast_tab(bf)
        target_hits[target_name] = hits
        print(f"  - {target_name}: {len(hits)} qualifying high-confidence hits")

    if not target_hits:
        return

    # Find universal intersection across ALL target genomes
    all_target_names = list(target_hits.keys())
    first_target = all_target_names[0]
    candidate_queries = set(target_hits[first_target].keys())

    for t_name in all_target_names[1:]:
        candidate_queries &= set(target_hits[t_name].keys())

    print(f"\n✨ Universal Conservation Intersection Complete!")
    print(f"   Found {len(candidate_queries)} cross-conserved STR loci present in ALL {len(all_target_names)} target comparison(s).")

    # Write detailed metadata table
    with open(OUTPUT_FILE, "w") as out:
        # Construct header
        header_cols = ["Query_Locus_ID", "Query_Chrom", "Query_Start", "Query_End", "STR_Motif"]
        for t_name in all_target_names:
            header_cols.extend([f"{t_name}_Chrom", f"{t_name}_Start", f"{t_name}_End", f"{t_name}_Pident", f"{t_name}_Coverage"])
        out.write("\t".join(header_cols) + "\n")

        for q_id in sorted(candidate_queries):
            parts = q_id.split("|")
            q_chrom = parts[1] if len(parts) > 1 else "Unknown"
            coords = parts[2].split("-") if len(parts) > 2 else ["0", "0"]
            motif = parts[3] if len(parts) > 3 else "Unknown"

            row = [q_id, q_chrom, coords[0], coords[1], motif]
            for t_name in all_target_names:
                hit = target_hits[t_name][q_id]
                row.extend([
                    str(hit["target_chrom"]),
                    str(hit["target_start"]),
                    str(hit["target_end"]),
                    f"{hit['pident']:.1f}",
                    f"{hit['coverage']:.1f}"
                ])
            out.write("\t".join(row) + "\n")

    print(f"💾 Saved master conserved locus coordinates to:\n   {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
